#!/usr/bin/env node
// Turns supabase/seed/food-catalog.json and starter-recipes.json into an
// idempotent migration (docs/nutrition-roadmap.md S1).
//
//   node scripts/generate-food-seed.mjs            # writes a new migration
//   node scripts/generate-food-seed.mjs --stdout   # prints SQL only
//
// Each run writes NEW timestamped files (one per part, applied in order);
// never edit an old seed migration.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const readJson = (path) => JSON.parse(readFileSync(new URL(path, root), "utf8"));

// Foods bought by count, so the grocery list can say "6 eggs".
const COUNT_UNIT_GRAMS = { "ing-egg": 50 };

export function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlNumber(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value !== "number" || !Number.isFinite(value)) {
    throw new Error(`Not a number: ${value}`);
  }
  return String(value);
}

function sqlTextArray(values) {
  if (!values || values.length === 0) return "'{}'::text[]";
  return `array[${values.map(sqlString).join(",")}]::text[]`;
}

function foodRow(food) {
  const serving = food.serving ?? {};
  return `(${[
    sqlString(food.slug),
    sqlString(food.kind),
    sqlString(food.region ?? null),
    sqlString(food.category ?? null),
    sqlString(food.name_en),
    sqlString(food.name_fa),
    sqlNumber(food.per_100g.kcal),
    sqlNumber(food.per_100g.protein),
    sqlNumber(food.per_100g.fat),
    sqlNumber(food.per_100g.carbs),
    sqlNumber(food.per_100g.fiber ?? 0),
    sqlNumber(serving.grams ?? null),
    sqlString(serving.unit ?? null),
    sqlString(serving.label_en ?? null),
    sqlString(serving.label_fa ?? null),
    sqlNumber(COUNT_UNIT_GRAMS[food.slug] ?? null),
    sqlString(food.grocery_section ?? null),
    food.is_staple ? "true" : "false",
    sqlTextArray(food.tags),
  ].join(", ")}, 'approximate')`;
}

function recipeRow(recipe) {
  return `(${[
    sqlString(recipe.slug),
    sqlString(recipe.title_en),
    sqlString(recipe.title_fa),
    sqlString(recipe.category),
    sqlNumber(recipe.servings),
    sqlTextArray(recipe.steps_en ?? []),
    sqlTextArray(recipe.steps_fa ?? []),
    sqlString(recipe.tip_en ?? null),
    sqlString(recipe.tip_fa ?? null),
    sqlTextArray(recipe.tags),
    sqlString(recipe.suggested_side?.food_slug ?? null),
    sqlNumber(recipe.suggested_side?.grams ?? null),
  ].join(", ")})`;
}

function ingredientRow(recipe, item, nameEnBySlug) {
  return `(${[
    sqlString(recipe.slug),
    sqlNumber(item.position),
    sqlString(item.food_slug),
    sqlString(item.name_en ?? (item.food_slug ? nameEnBySlug.get(item.food_slug) : null)),
    sqlString(item.name_fa),
    sqlNumber(item.grams),
    sqlString(item.amount_en ?? null),
    sqlString(item.amount_fa ?? null),
    item.is_staple ? "true" : "false",
  ].join(", ")})`;
}

export function validate(catalog, recipes) {
  const foods = [...catalog.ingredients, ...catalog.dishes];
  const slugs = new Set();
  for (const food of foods) {
    if (slugs.has(food.slug)) throw new Error(`Duplicate food slug ${food.slug}`);
    slugs.add(food.slug);
  }
  for (const recipe of recipes) {
    for (const item of recipe.ingredients) {
      if (item.food_slug && !slugs.has(item.food_slug)) {
        throw new Error(`${recipe.slug}: dangling food slug ${item.food_slug}`);
      }
      if (!item.food_slug && !item.name_fa && !item.name_en) {
        throw new Error(`${recipe.slug}: ingredient without food or name`);
      }
    }
    const side = recipe.suggested_side?.food_slug;
    if (side && !slugs.has(side)) throw new Error(`${recipe.slug}: dangling side ${side}`);
  }
  return foods;
}

const HEADER = `-- Generated by scripts/generate-food-seed.mjs from supabase/seed/*.json.
-- Do not edit by hand: change the JSON and generate a new migration.`;

const FOOD_COLUMNS = `insert into public.foods (slug, kind, region, category, name_en, name_fa,
  kcal_100g, protein_100g, fat_100g, carbs_100g, fiber_100g,
  serving_grams, serving_unit, serving_label_en, serving_label_fa,
  count_unit_grams, grocery_section, is_staple, tags, source)
values`;

const FOOD_CONFLICT = `on conflict (slug) do update set
  kind = excluded.kind, region = excluded.region, category = excluded.category,
  name_en = excluded.name_en, name_fa = excluded.name_fa,
  kcal_100g = excluded.kcal_100g, protein_100g = excluded.protein_100g,
  fat_100g = excluded.fat_100g, carbs_100g = excluded.carbs_100g,
  fiber_100g = excluded.fiber_100g, serving_grams = excluded.serving_grams,
  serving_unit = excluded.serving_unit, serving_label_en = excluded.serving_label_en,
  serving_label_fa = excluded.serving_label_fa, count_unit_grams = excluded.count_unit_grams,
  grocery_section = excluded.grocery_section, is_staple = excluded.is_staple,
  tags = excluded.tags, source = excluded.source;`;

/**
 * The seed as ordered, self-contained parts (each small enough to apply on its
 * own). Apply them in order: foods, then recipes, then recipe ingredients.
 */
export function buildSeedParts(catalog, recipeFile) {
  const recipes = recipeFile.recipes;
  const foods = validate(catalog, recipes);
  const nameEnBySlug = new Map(foods.map((food) => [food.slug, food.name_en]));
  const ingredients = recipes.flatMap((recipe) =>
    recipe.ingredients.map((item) => ingredientRow(recipe, item, nameEnBySlug)),
  );
  const recipeSlugs = recipes.map((recipe) => sqlString(recipe.slug)).join(", ");
  const foodGroups = [
    ["foods_ingredients", catalog.ingredients],
    ["foods_iran", catalog.dishes.filter((dish) => dish.region === "iran")],
    ["foods_global", catalog.dishes.filter((dish) => dish.region !== "iran")],
  ];

  const parts = foodGroups.map(([name, group]) => ({
    name: `seed_food_catalog_${name}`,
    sql: `${HEADER}
-- ${group.length} of ${foods.length} catalog foods.

${FOOD_COLUMNS}
${group.map(foodRow).join(",\n")}
${FOOD_CONFLICT}
`,
  }));

  parts.push({
    name: "seed_food_catalog_recipes",
    sql: `${HEADER}
-- ${recipes.length} starter recipes (needs the catalog foods for suggested sides).

insert into public.recipes (slug, title_en, title_fa, category, servings,
  steps_en, steps_fa, tip_en, tip_fa, tags, suggested_side_food_id, suggested_side_grams)
select v.slug, v.title_en, v.title_fa, v.category, v.servings, v.steps_en, v.steps_fa,
  v.tip_en, v.tip_fa, v.tags, f.id, v.side_grams
from (values
${recipes.map(recipeRow).join(",\n")}
) as v(slug, title_en, title_fa, category, servings, steps_en, steps_fa, tip_en, tip_fa, tags, side_slug, side_grams)
left join public.foods f on f.slug = v.side_slug
on conflict (slug) do update set
  title_en = excluded.title_en, title_fa = excluded.title_fa, category = excluded.category,
  servings = excluded.servings, steps_en = excluded.steps_en, steps_fa = excluded.steps_fa,
  tip_en = excluded.tip_en, tip_fa = excluded.tip_fa, tags = excluded.tags,
  suggested_side_food_id = excluded.suggested_side_food_id,
  suggested_side_grams = excluded.suggested_side_grams;
`,
  });

  parts.push({
    name: "seed_food_catalog_ingredients",
    sql: `${HEADER}
-- ${ingredients.length} starter recipe ingredients (needs the foods and recipes parts).

-- Catalog ingredients have no natural key: replace them for the seeded recipes.
delete from public.recipe_ingredients ri
using public.recipes r
where ri.recipe_id = r.id and ri.owner_id is null and r.owner_id is null
  and r.slug in (${recipeSlugs});

insert into public.recipe_ingredients (recipe_id, owner_id, position, food_id,
  name_en, name_fa, grams, amount_en, amount_fa, is_staple)
select r.id, null, v.position, f.id, v.name_en, v.name_fa, v.grams, v.amount_en, v.amount_fa, v.is_staple
from (values
${ingredients.join(",\n")}
) as v(recipe_slug, position, food_slug, name_en, name_fa, grams, amount_en, amount_fa, is_staple)
join public.recipes r on r.slug = v.recipe_slug and r.owner_id is null
left join public.foods f on f.slug = v.food_slug;
`,
  });
  return parts;
}

function timestamp(date = new Date()) {
  const pad = (n) => String(n).padStart(2, "0");
  return `${date.getUTCFullYear()}${pad(date.getUTCMonth() + 1)}${pad(date.getUTCDate())}${pad(
    date.getUTCHours(),
  )}${pad(date.getUTCMinutes())}${pad(date.getUTCSeconds())}`;
}

if (process.argv[1]?.endsWith("generate-food-seed.mjs")) {
  const parts = buildSeedParts(
    readJson("supabase/seed/food-catalog.json"),
    readJson("supabase/seed/starter-recipes.json"),
  );
  if (process.argv.includes("--stdout")) {
    process.stdout.write(parts.map((part) => part.sql).join("\n"));
  } else {
    // One file per part, one second apart so they sort in apply order.
    const start = Date.now();
    parts.forEach((part, index) => {
      const file = `supabase/migrations/${timestamp(new Date(start + index * 1000))}_${part.name}.sql`;
      writeFileSync(new URL(file, root), part.sql);
      console.log(`Wrote ${file} (${Buffer.byteLength(part.sql)} bytes)`);
    });
  }
}
